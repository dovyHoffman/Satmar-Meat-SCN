create temp table mnk as select mi.*, lower(regexp_replace(trim(name),'\s+',' ','g')) nk from mi;
insert into raw_items (name,name_key,section,case_price,units_per_case,last_used,uses)
select min(m.name), m.nk, 'meat', (array_agg(m.price order by w.week_date desc) filter (where m.price is not null))[1], 1, max(w.week_date), count(distinct w.id)
from mnk m join raw_weeks w on w.label=m.week_label group by m.nk
on conflict (name_key) do nothing;
insert into raw_week_items (week_id,item_id,section,name,vendor,qty,units_per_case,case_price,sort)
select w.id, r.id, 'meat', m.name, '', m.qty, 1, m.price, m.sort
from mnk m join raw_weeks w on w.label=m.week_label join raw_items r on r.name_key=m.nk
where not exists (select 1 from raw_week_items x where x.week_id=w.id and x.section='meat');
insert into raw_week_counts (week_id,code,ordered)
select w.id, c.code, c.n from mc c join raw_weeks w on w.label=c.week_label
on conflict (week_id,code) do update set ordered = coalesce(raw_week_counts.ordered, excluded.ordered);
